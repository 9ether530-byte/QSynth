/**
 * OpenQASM 3.0 emission.
 *
 * Deterministic by construction: no timestamps, no absolute paths, no iteration over
 * unordered collections. The same circuit emits byte-identical text on every machine,
 * which is what makes the content hash in FR-7 a reproducibility guarantee rather than
 * a hope. Anything varying per-run belongs in the job record, not in the artifact.
 *
 * **The emitted circuit is the Clifford+T one, not the reversible one.** A `ccx` in the
 * output would be shorter to read, but it would also be a gate no fault-tolerant machine
 * executes — the T count a user budgeted against would live in our estimate and nowhere
 * in the artifact they hold, and whichever toolchain they hand it to would decompose it
 * its own way. Emitting the decomposition means the file they run is the circuit that was
 * verified, gate for gate. The reversible form is not lost: it is kept as its own
 * artifact, and it is what the circuit diagram and the gate list below render.
 *
 * Only gates from `stdgates.inc` are used, so the output parses in any conforming
 * toolchain without a custom prelude.
 */
import type { ReversibleCircuit } from '../ir/reversible.js';
import type { QuantumCircuit } from '../ir/quantum.js';
import { tCount, tDepth } from '../ir/quantum.js';
import { assertInvariant } from '../errors.js';

export interface QasmOptions {
  readonly compilerVersion: string;
  readonly specHash: string;
  /** Emit `measure` into a classical register for each output wire. */
  readonly measure?: boolean;
}

const QASM_GATE: Record<string, string> = {
  x: 'x',
  y: 'y',
  z: 'z',
  h: 'h',
  s: 's',
  sdg: 'sdg',
  t: 't',
  tdg: 'tdg',
  cx: 'cx',
};

export function emitQasm3(circuit: QuantumCircuit, options: QasmOptions): string {
  const lines: string[] = [];
  const measure = options.measure ?? true;

  lines.push('OPENQASM 3.0;');
  lines.push('include "stdgates.inc";');
  lines.push('');
  lines.push(`// ${circuit.name} — generated by qsynth ${options.compilerVersion}`);
  lines.push(`// spec ${options.specHash}`);
  lines.push(`// basis ${circuit.basis}: ${circuit.gates.length} gates, ${tCount(circuit)} T, T-depth ${tDepth(circuit)}`);
  lines.push('//');
  lines.push('// Wire map:');
  for (const wire of circuit.wires) {
    lines.push(`//   q[${wire.index}]  ${pad(wire.role, 7)} ${wire.name}`);
  }
  lines.push('');
  lines.push(`qubit[${circuit.wires.length}] q;`);
  if (measure && circuit.outputs.length > 0) lines.push(`bit[${circuit.outputs.length}] c;`);
  lines.push('');

  for (const gate of circuit.gates) {
    const name = QASM_GATE[gate.kind];
    assertInvariant(name !== undefined, `no OpenQASM mapping for gate ${gate.kind}`);
    lines.push(`${name} ${gate.wires.map((w) => `q[${w}]`).join(', ')};`);
  }

  if (measure && circuit.outputs.length > 0) {
    lines.push('');
    circuit.outputs.forEach((output, i) => {
      lines.push(`c[${i}] = measure q[${output.wire}];  // ${output.name}`);
    });
  }

  lines.push('');
  return lines.join('\n');
}

function pad(text: string, width: number): string {
  return text.length >= width ? text : text + ' '.repeat(width - text.length);
}

/**
 * The gate list as text (FR-9.5) — the screen-reader equivalent of the circuit diagram.
 * Generated from the same circuit the SVG renders, so the two cannot drift apart.
 */
export function gateListText(circuit: ReversibleCircuit): string {
  const label = (w: number) => {
    const wire = circuit.wires[w]!;
    return `${wire.name} (q${w})`;
  };
  return circuit.gates
    .map((gate, i) => {
      switch (gate.kind) {
        case 'x':
          return `${i + 1}. NOT on ${label(gate.wires[0]!)}`;
        case 'cnot':
          return `${i + 1}. controlled-NOT: control ${label(gate.wires[0]!)}, target ${label(gate.wires[1]!)}`;
        case 'ccnot':
          return `${i + 1}. Toffoli: controls ${label(gate.wires[0]!)} and ${label(gate.wires[1]!)}, target ${label(gate.wires[2]!)}`;
        case 'cswap':
          return `${i + 1}. Fredkin: control ${label(gate.wires[0]!)}, swapping ${label(gate.wires[1]!)} and ${label(gate.wires[2]!)}`;
      }
    })
    .join('\n');
}
