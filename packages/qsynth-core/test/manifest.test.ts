/**
 * The corpus manifest — one committed table freezing what every golden circuit costs.
 *
 * The per-circuit `.qasm` snapshots already catch output changes, but they catch them one
 * file at a time and a resource regression hides inside a long gate diff. The manifest is
 * the other view: every circuit's qubits, gates, depth and T-count on one line each, so a
 * change that makes twelve circuits 5% bigger is twelve visible lines in one file rather
 * than something nobody adds up.
 *
 * `specHash` and `artifactHash` are here for a second reason. They are what the API stores
 * and what the export gate checks, so pinning them makes reproducibility (FR-7) a
 * committed fact rather than a property a separate test asserts about a single run.
 *
 * Regenerate with `npm run docs:manifest`, and explain the diff in review.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { compile, COMPILER_VERSION } from '@qsynth/core';
import { CORPUS } from './corpus.js';

const MANIFEST_PATH = fileURLToPath(new URL('./golden/MANIFEST.md', import.meta.url));

/** Everything about a compiled circuit that a change in the compiler could move. */
function measure(entry: (typeof CORPUS)[number]) {
  const result = compile({ kind: entry.kind, source: entry.source, name: entry.name });
  return {
    name: entry.name,
    kind: entry.kind,
    inputs: result.module.inputs.length,
    // Declared assertions get their own wire, so they cost a qubit like any other output
    // and are counted in their own column rather than folded into the result count — a
    // circuit is not wider than its specification implies, but it is not free either.
    outputs: result.circuit.outputs.filter((o) => !o.name.startsWith('assert:')).length,
    asserts: result.circuit.outputs.filter((o) => o.name.startsWith('assert:')).length,
    qubits: result.estimate.qubits,
    ancillas: result.estimate.ancillaQubits,
    gates: result.estimate.gateCount,
    depth: result.estimate.depth,
    tCount: result.estimate.cliffordT.tCount,
    tDepth: result.estimate.cliffordT.tDepth,
    specHash: result.specHash,
    artifactHash: result.artifactHash,
  };
}

function renderManifest(): string {
  const rows = CORPUS.map(measure);
  const total = (key: 'qubits' | 'gates' | 'tCount') => rows.reduce((sum, r) => sum + r[key], 0);

  const lines = [
    '# Golden corpus manifest',
    '',
    '<!-- Generated by `npm run docs:manifest`. Do not edit by hand. -->',
    '',
    `Compiler version \`${COMPILER_VERSION}\`. ${rows.length} circuits, ` +
      `${total('gates')} reversible gates, ${total('tCount')} T gates in total.`,
    '',
    'Every circuit here passes all six checks and is verified exhaustively against an',
    'independently written reference on every input assignment — see `golden.test.ts`.',
    'This file freezes what they *cost*. A diff means the compiler changed its output:',
    'legitimate when a pass got smarter, a regression when it did not, and never something',
    'to regenerate without reading.',
    '',
    '| Circuit | Kind | In | Out | Assert | Ancilla | Qubits | Gates | Depth | T | T-depth |',
    '| --- | --- | --: | --: | --: | --: | --: | --: | --: | --: | --: |',
    ...rows.map(
      (r) =>
        `| \`${r.name}\` | ${r.kind} | ${r.inputs} | ${r.outputs} | ${r.asserts} | ` +
        `${r.ancillas} | ${r.qubits} | ${r.gates} | ${r.depth} | ${r.tCount} | ${r.tDepth} |`,
    ),
    '',
    'Qubits is the sum of the four columns before it: nothing in a compiled circuit is',
    'unaccounted for, which is what makes the garbage-free check meaningful.',
    '',
    '## Content hashes',
    '',
    'The spec hash identifies the input, the artifact hash the emitted QASM. The API stores',
    'both, and the export gate matches a verification report to an artifact by the second',
    'one — so an artifact hash moving while its spec hash holds still means identical input',
    'now compiles to different bytes.',
    '',
    '| Circuit | Spec hash | Artifact hash |',
    '| --- | --- | --- |',
    ...rows.map((r) => `| \`${r.name}\` | \`${r.specHash.slice(0, 16)}\` | \`${r.artifactHash.slice(0, 16)}\` |`),
    '',
  ];
  return lines.join('\n');
}

describe('the golden corpus manifest', () => {
  it('matches the committed manifest', () => {
    const rendered = renderManifest();
    if (process.env['UPDATE_DOCS']) {
      writeFileSync(MANIFEST_PATH, rendered);
      return;
    }
    expect(
      readFileSync(MANIFEST_PATH, 'utf8'),
      'the corpus changed cost — run `npm run docs:manifest` and explain the diff',
    ).toBe(rendered);
  });

  it('reports the same figures on a second compile of the same source', () => {
    // The manifest is only worth freezing if it is deterministic. Compiling twice and
    // comparing every measured field is a sharper reproducibility check than comparing
    // output bytes alone: it also covers the estimator, which reads the circuit rather
    // than the QASM and could drift from it.
    for (const entry of CORPUS) {
      expect(measure(entry), entry.name).toEqual(measure(entry));
    }
  });

  it('accounts for every qubit it reports', () => {
    // If the width did not decompose exactly into inputs, results, assertions and
    // ancillas, some wire would exist in the circuit without a role in the ledger — and
    // an unaccounted wire is precisely the thing the garbage-free check cannot vouch for.
    for (const row of CORPUS.map(measure)) {
      expect(row.qubits, row.name).toBe(row.inputs + row.outputs + row.asserts + row.ancillas);
    }
  });
});
