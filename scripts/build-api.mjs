/**
 * Bundles functions/api/src/handler.ts (+ the qsynth-core package) into a single
 * functions/api/index.mjs, which is committed so deploys are reproducible.
 *
 * `pg` stays external — it is installed into functions/api/node_modules and zipped
 * by the CLI. Bundling it would inflate the artifact and break its native-ish
 * lazy requires.
 */
import { build } from 'esbuild';
import { stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const outfile = fileURLToPath(new URL('functions/api/index.mjs', root));

// The platform caps the deploy request at ~6 MB and the practical bundle limit is
// ~4 MB zipped. Assert well under it so growth is caught at build time, not at a
// raw 502 from the deploy endpoint.
const MAX_BUNDLE_BYTES = 2_000_000;

const result = await build({
  entryPoints: [fileURLToPath(new URL('functions/api/src/handler.ts', root))],
  outfile,
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  sourcemap: false,
  minify: false, // readable stack traces in CloudWatch beat a few hundred KB
  legalComments: 'none',
  external: ['pg', '@aws-sdk/*'],
  banner: {
    js: '// GENERATED by scripts/build-api.mjs — do not edit. Source: functions/api/src/',
  },
  metafile: true,
});

const { size } = await stat(outfile);
const kb = (size / 1024).toFixed(1);

if (size > MAX_BUNDLE_BYTES) {
  console.error(`✗ api bundle is ${kb} KB, over the ${MAX_BUNDLE_BYTES / 1024} KB budget.`);
  console.error('  Largest inputs:');
  const inputs = Object.entries(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs)
    .sort((a, b) => b[1].bytesInOutput - a[1].bytesInOutput)
    .slice(0, 10);
  for (const [name, info] of inputs) {
    console.error(`    ${(info.bytesInOutput / 1024).toFixed(1).padStart(8)} KB  ${name}`);
  }
  process.exit(1);
}

console.log(`✓ api bundle ${kb} KB (budget ${MAX_BUNDLE_BYTES / 1024} KB)`);
