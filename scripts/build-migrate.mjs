/**
 * Bundles the migration runner. The SQL files themselves are inlined at build time
 * so the deployed function carries its migrations with it — no S3 fetch, no drift
 * between the code that runs and the SQL it thinks it has.
 */
import { build } from 'esbuild';
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const migrationsDir = fileURLToPath(new URL('migrations/', root));
const genDir = fileURLToPath(new URL('functions/migrate/src/generated/', root));

const files = (await readdir(migrationsDir)).filter((f) => f.endsWith('.sql')).sort();

const entries = [];
for (const name of files) {
  const sql = await readFile(new URL(name, new URL('migrations/', root)), 'utf8');
  entries.push({ name, sql });
}

await mkdir(genDir, { recursive: true });
await writeFile(
  `${genDir}migrations.ts`,
  `// GENERATED by scripts/build-migrate.mjs — do not edit.\n` +
    `export interface Migration { readonly name: string; readonly sql: string }\n` +
    `export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(entries, null, 2)};\n`,
  'utf8',
);

await build({
  entryPoints: [fileURLToPath(new URL('functions/migrate/src/handler.ts', root))],
  outfile: fileURLToPath(new URL('functions/migrate/index.mjs', root)),
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  external: ['pg', '@aws-sdk/*'],
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-migrate.mjs — do not edit.' },
});

console.log(`✓ migrate bundle (${files.length} migration${files.length === 1 ? '' : 's'} inlined)`);
